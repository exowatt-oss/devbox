function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`
}

function xmlEscape(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;')
}

function systemdValue(value: string): string {
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(value)) {
    return value
  }
  return `"${systemdEscape(value)}"`
}

function systemdEscape(value: string): string {
  return value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')
}

function systemdEnvironment(name: string, value: string): string {
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(value)) {
    return `${name}=${value}`
  }
  return `"${systemdEscape(`${name}=${value}`)}"`
}

export function renderMutagenWrapperScript(input: {
  binaryPath: string
  dataDirectory: string
  devboxVersion: string
  home: string
}): string {
  const binaryPath = shellQuote(input.binaryPath)
  const dataDirectory = shellQuote(input.dataDirectory)
  const home = shellQuote(input.home)
  return `#!/bin/sh
# generated by devbox mutagen setup (devbox ${input.devboxVersion}) — do not edit, re-run setup
set -u
export HOME=${home}
export MUTAGEN_DATA_DIRECTORY=${dataDirectory}
BIN=${binaryPath}
child=''
trap 'if [ -n "$child" ]; then kill -TERM "$child" 2>/dev/null || true; wait "$child" 2>/dev/null || true; fi; exit 0' TERM INT HUP

candidate_version() {
  candidate_dir=\${1%/mutagen}
  case "$candidate_dir" in
    */extracted) candidate_dir=\${candidate_dir%/extracted} ;;
  esac
  candidate_name=\${candidate_dir##*/}
  printf '%s\\n' "\${candidate_name#mutagen-}"
}

version_is_newer() {
  awk -v left="$1" -v right="$2" '
    BEGIN {
      leftCount = split(left, leftParts, ".")
      rightCount = split(right, rightParts, ".")
      count = leftCount > rightCount ? leftCount : rightCount
      for (partIndex = 1; partIndex <= count; partIndex += 1) {
        leftPart = (leftParts[partIndex] == "" ? 0 : leftParts[partIndex] + 0)
        rightPart = (rightParts[partIndex] == "" ? 0 : rightParts[partIndex] + 0)
        if (leftPart != rightPart) {
          exit leftPart > rightPart ? 0 : 1
        }
      }
      exit left > right ? 0 : 1
    }
  '
}

pick_binary() {
  if [ -x "$BIN" ]; then
    printf '%s\\n' "$BIN"
    return
  fi
  best=''
  best_version=''
  for candidate in "$HOME"/.local/state/devbox/tools/mutagen-*/mutagen "$HOME"/.local/opt/mutagen-*/extracted/mutagen; do
    [ -x "$candidate" ] || continue
    candidate_version_value=$(candidate_version "$candidate")
    if [ -z "$best" ] || version_is_newer "$candidate_version_value" "$best_version" || { [ "$candidate_version_value" = "$best_version" ] && [ "$candidate" \\> "$best" ]; }; then
      best=$candidate
      best_version=$candidate_version_value
    fi
  done
  printf '%s\\n' "$best"
}

log() {
  printf '%s devbox-mutagen-daemon: %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >&2
}

while :; do
  bin=$(pick_binary)
  if [ -z "$bin" ]; then
    log "no devbox-managed mutagen; retrying in 300s"
    sleep 300
    continue
  fi
  start=$(date +%s)
  "$bin" daemon run &
  child=$!
  wait "$child"
  rc=$?
  child=''
  elapsed=$(( $(date +%s) - start ))
  if [ "$elapsed" -lt 5 ]; then
    log "exited rc=$rc after \${elapsed}s (daemon lock held by another daemon?) — retrying in 60s"
    sleep 60
  else
    log "exited rc=$rc; restarting in 15s"
    sleep 15
  fi
done
`
}

/**
 * `ProcessType` is `Standard`, never `Background`: a Background job and every child it
 * spawns (Mutagen's ssh, a `devbox proxy` ProxyCommand, its curl and nc) run under darwin
 * background QoS, and on a loaded Mac they starve until ssh gives up with `Connection timed
 * out during banner exchange`, so `db sync` could not reach a box a shell reaches in 1 s.
 */
export function renderLaunchdPlist(input: {
  label: string
  wrapperPath: string
  dataDirectory: string
  logPath: string
  home: string
}): string {
  const value = (text: string): string => xmlEscape(text)
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${value(input.label)}</string>
  <key>ProgramArguments</key><array><string>${value(input.wrapperPath)}</string></array>
  <key>EnvironmentVariables</key><dict>
    <key>MUTAGEN_DATA_DIRECTORY</key><string>${value(input.dataDirectory)}</string>
    <key>HOME</key><string>${value(input.home)}</string>
    <key>PATH</key><string>/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin:/usr/local/bin</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>30</integer>
  <key>ProcessType</key><string>Standard</string>
  <key>StandardOutPath</key><string>${value(input.logPath)}</string>
  <key>StandardErrorPath</key><string>${value(input.logPath)}</string>
</dict></plist>
`
}

export function renderSystemdUnit(input: {
  wrapperPath: string
  dataDirectory: string
  logPath: string
}): string {
  return `[Unit]
Description=Devbox app-private Mutagen daemon (keepalive)

[Service]
Type=simple
ExecStart=${systemdValue(input.wrapperPath)}
Environment=${systemdEnvironment('MUTAGEN_DATA_DIRECTORY', input.dataDirectory)}
Restart=always
RestartSec=15
KillMode=control-group
StandardOutput=append:${systemdValue(input.logPath)}
StandardError=append:${systemdValue(input.logPath)}

[Install]
WantedBy=default.target
`
}
