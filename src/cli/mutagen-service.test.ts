import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { spawn, spawnSync } from 'node:child_process'
import { once } from 'node:events'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { MUTAGEN_SERVICE_LAUNCHD_LABEL, MUTAGEN_SERVICE_SYSTEMD_UNIT } from './hub-types'
import { createMutagenDaemonService, mutagenServicePaths, parseLaunchctlPrint } from './mutagen-service'
import { renderLaunchdPlist, renderMutagenWrapperScript, renderSystemdUnit } from './mutagen-service-wrapper'

type Call = { command: string; args: readonly string[] }

function tempRoot(): string {
  return mkdtempSync(join(tmpdir(), 'devbox-mutagen-service-'))
}

function options(root: string, platform: NodeJS.Platform, exec: (command: string, args: readonly string[]) => Promise<{ exitCode: number; stdout: string; stderr: string }>) {
  return { stateRoot: join(root, 'state'), home: join(root, 'home'), platform, env: {}, devboxVersion: '0.2.17', exec }
}

describe('Mutagen service renderers', () => {
  it('renders a POSIX wrapper with safe paths and all keepalive branches', () => {
    const wrapper = renderMutagenWrapperScript({ binaryPath: "/tmp/baked path/it's-mutagen", dataDirectory: "/tmp/state path/it's-mutagen", devboxVersion: '1.2.3', home: "/tmp/home path/it's-home" })
    expect(wrapper).toContain('generated by devbox mutagen setup (devbox 1.2.3)')
    expect(wrapper).toContain("BIN='/tmp/baked path/it'\\''s-mutagen'")
    expect(wrapper).toContain("MUTAGEN_DATA_DIRECTORY='/tmp/state path/it'\\''s-mutagen'")
    expect(wrapper).toContain('set -u')
    expect(wrapper).toContain('retrying in 300s')
    expect(wrapper).toContain('retrying in 60s')
    expect(wrapper).toContain('restarting in 15s')
    expect(wrapper).not.toMatch(/\[\[/u)
    const root = tempRoot()
    const wrapperPath = join(root, 'wrapper.sh')
    writeFileSync(wrapperPath, wrapper, { mode: 0o755 })
    expect(spawnSync('sh', ['-n', wrapperPath], { encoding: 'utf8' }).status).toBe(0)
    rmSync(root, { recursive: true, force: true })
  })

  it('forwards termination signals to the daemon child', async () => {
    const root = tempRoot()
    const binaryPath = join(root, 'mutagen')
    const terminatedPath = join(root, 'terminated')
    writeFileSync(binaryPath, `#!/bin/sh
PID_FILE='${join(root, 'child.pid')}'
TERMINATED_FILE='${terminatedPath}'
trap 'printf terminated > "$TERMINATED_FILE"; exit 0' TERM INT HUP
printf '%s\\n' "$$" > "$PID_FILE"
while :; do sleep 1; done
`, { mode: 0o755 })
    const wrapperPath = join(root, 'wrapper.sh')
    writeFileSync(wrapperPath, renderMutagenWrapperScript({ binaryPath, dataDirectory: join(root, 'data'), devboxVersion: '1.2.3', home: root }), { mode: 0o755 })
    const child = spawn('sh', [wrapperPath], { stdio: 'ignore' })
    try {
      const readyDeadline = Date.now() + 10_000
      while (Date.now() < readyDeadline && !existsSync(join(root, 'child.pid'))) {
        await new Promise((resolve) => setTimeout(resolve, 20))
      }
      expect(existsSync(join(root, 'child.pid'))).toBe(true)
      child.kill('SIGTERM')
      await once(child, 'exit')
      const terminationDeadline = Date.now() + 10_000
      while (Date.now() < terminationDeadline && !existsSync(terminatedPath)) {
        await new Promise((resolve) => setTimeout(resolve, 20))
      }
      expect(readFileSync(terminatedPath, 'utf8')).toBe('terminated')
    } finally {
      if (child.exitCode === null) {child.kill('SIGKILL')}
      rmSync(root, { recursive: true, force: true })
    }
  })

  it('renders XML-safe launchd and correctly quoted systemd values', () => {
    const plist = renderLaunchdPlist({ label: 'com.example', wrapperPath: "/tmp/wrapper & <one>", dataDirectory: "/tmp/data & <two>", logPath: "/tmp/log & <three>", home: "/tmp/home & <four>" })
    expect(plist).toContain('/tmp/wrapper &amp; &lt;one&gt;')
    expect(plist).toContain('/tmp/data &amp; &lt;two&gt;')
    expect(plist).toContain('/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin:/usr/local/bin')
    // Background QoS starves the daemon's ssh/ProxyCommand children on a loaded Mac.
    expect(plist).toContain('<key>ProcessType</key><string>Standard</string>')
    expect(plist).not.toContain('Background')
    const unit = renderSystemdUnit({ wrapperPath: '/tmp/wrapper path', dataDirectory: '/tmp/data path', logPath: '/tmp/log path' })
    expect(unit).toContain('ExecStart="/tmp/wrapper path"')
    expect(unit).toContain('Environment="MUTAGEN_DATA_DIRECTORY=/tmp/data path"')
    expect(unit).toContain('StandardOutput=append:"/tmp/log path"')
    expect(unit).toContain('WantedBy=default.target')
  })
})

describe('launchd Mutagen service', () => {
  it('parses realistic launchctl print output', () => {
    expect(parseLaunchctlPrint('path = /tmp/service.plist\nactive count = 1\nstate = running\npid = 16508\nprogram = /tmp/wrapper\n')).toEqual({ state: 'running', pid: 16508 })
  })

  let root: string | undefined
  afterEach(() => { if (root) {rmSync(root, { recursive: true, force: true });} root = undefined })

  it('installs, preserves an unchanged running service, updates, stops, and uninstalls', async () => {
    root = tempRoot()
    let loaded = false
    let running = false
    const calls: Call[] = []
    const exec = async (command: string, args: readonly string[]) => {
      calls.push({ command, args })
      if (command !== 'launchctl') {return { exitCode: 0, stdout: '', stderr: '' }}
      if (args[0] === 'print') {return loaded ? { exitCode: 0, stdout: `state = ${running ? 'running' : 'waiting'}\npid = 16508\n`, stderr: '' } : { exitCode: 3, stdout: '', stderr: 'Could not find service' }}
      if (args[0] === 'bootstrap') { loaded = true; running = true; return { exitCode: 0, stdout: '', stderr: '' } }
      if (args[0] === 'bootout') { loaded = false; running = false; return { exitCode: 0, stdout: '', stderr: '' } }
      if (args[0] === 'kickstart') { running = true; return { exitCode: 0, stdout: '', stderr: '' } }
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const service = createMutagenDaemonService(options(root, 'darwin', exec))
    const first = await service.install({ binaryPath: '/tmp/mutagen', dataDirectory: join(root, 'mutagen') })
    expect(first.action).toBe('installed')
    expect(statSync(join(root, 'state')).mode & 0o777).toBe(0o700)
    expect(statSync(join(root, 'state/bin')).mode & 0o777).toBe(0o700)
    expect(statSync(mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'darwin', env: {} }).wrapperPath).mode & 0o777).toBe(0o755)
    expect(statSync(mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'darwin', env: {} }).unitPath).mode & 0o777).toBe(0o644)
    expect(calls.some((call) => call.args[0] === 'bootstrap')).toBe(true)
    calls.length = 0
    const second = await service.install({ binaryPath: '/tmp/mutagen', dataDirectory: join(root, 'mutagen') })
    expect(second.action).toBe('unchanged')
    expect(calls.some((call) => call.args[0] === 'bootout' || call.args[0] === 'bootstrap')).toBe(false)
    const changed = await service.install({ binaryPath: '/tmp/other-mutagen', dataDirectory: join(root, 'mutagen') })
    expect(changed.action).toBe('updated')
    expect(calls.filter((call) => call.args[0] === 'bootout' || call.args[0] === 'bootstrap').map((call) => call.args[0])).toEqual(['bootout', 'bootstrap'])
    await service.stop()
    expect(calls.some((call) => call.args[0] === 'bootout')).toBe(true)
    await service.uninstall()
    const paths = mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'darwin', env: {} })
    expect(() => readFileSync(paths.wrapperPath)).toThrow()
    expect(() => readFileSync(paths.unitPath)).toThrow()
    expect(MUTAGEN_SERVICE_LAUNCHD_LABEL).toBe(paths.label)
  })
  it('replaces a loaded legacy LaunchAgent instead of treating it as unchanged', async () => {
    root = tempRoot()
    const calls: Call[] = []
    let loaded = true
    let running = true
    const exec = async (command: string, args: readonly string[]) => {
      calls.push({ command, args })
      if (args[0] === 'print') {
        return loaded
          ? { exitCode: 0, stdout: 'path = /Users/sample/Library/LaunchAgents/legacy.plist\nactive count = 1\nstate = running\npid = 16508\nprogram = /Users/sample/.local/bin/devbox-mutagen-daemon\n', stderr: '' }
          : { exitCode: 3, stdout: '', stderr: 'Could not find service' }
      }
      if (args[0] === 'bootout') { loaded = false; running = false; return { exitCode: 0, stdout: '', stderr: '' } }
      if (args[0] === 'bootstrap') { loaded = true; running = true; return { exitCode: 0, stdout: '', stderr: '' } }
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const paths = mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'darwin', env: {} })
    mkdirSync(join(root, 'home/Library/LaunchAgents'), { recursive: true })
    writeFileSync(paths.unitPath, `<plist><dict><key>Label</key><string>${MUTAGEN_SERVICE_LAUNCHD_LABEL}</string><key>ProgramArguments</key><array><string>${join(root, 'home/.local/bin/devbox-mutagen-daemon')}</string></array></dict></plist>`)
    const service = createMutagenDaemonService(options(root, 'darwin', exec))
    const result = await service.install({ binaryPath: '/tmp/new-mutagen', dataDirectory: join(root, 'mutagen') })
    expect(result.action).toBe('updated')
    expect(calls.map((call) => call.args[0]).filter((value) => value === 'bootout' || value === 'bootstrap')).toEqual(['bootout', 'bootstrap'])
    expect(running).toBe(true)
  })

  it('waits out an asynchronous bootout before bootstrapping an updated service', async () => {
    root = tempRoot()
    const calls: Call[] = []
    // launchd: bootout returns while the old job still tears down; a bootstrap in that window
    // answers 37 without loading; the next bootstrap after teardown loads the job.
    let state: 'loaded' | 'tearing-down' | 'gone' = 'loaded'
    let printsWhileTearingDown = 0
    let refusedBootstraps = 0
    const exec = async (command: string, args: readonly string[]) => {
      calls.push({ command, args })
      if (args[0] === 'print') {
        if (state === 'tearing-down' && (printsWhileTearingDown += 1) > 2) {state = 'gone'}
        return state === 'gone' ? { exitCode: 113, stdout: '', stderr: 'Could not find service' } : { exitCode: 0, stdout: 'state = running\npid = 4242\n', stderr: '' }
      }
      if (args[0] === 'bootout') { state = 'tearing-down'; return { exitCode: 0, stdout: '', stderr: '' } }
      if (args[0] === 'bootstrap') {
        if (state !== 'gone' || refusedBootstraps === 0) { refusedBootstraps += 1; return { exitCode: 37, stdout: '', stderr: 'Bootstrap failed: 37: Operation already in progress' } }
        state = 'loaded'
        return { exitCode: 0, stdout: '', stderr: '' }
      }
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const service = createMutagenDaemonService(options(root, 'darwin', exec))
    const paths = mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'darwin', env: {} })
    mkdirSync(join(root, 'home/Library/LaunchAgents'), { recursive: true })
    writeFileSync(paths.unitPath, '<plist>stale</plist>')
    const result = await service.install({ binaryPath: '/tmp/mutagen', dataDirectory: join(root, 'mutagen') })
    expect(result.action).toBe('updated')
    expect(result.state).toMatchObject({ loaded: true, running: true })
    expect(result.state.detail).toBeUndefined()
    const order = calls.map((call) => call.args[0]).filter((value) => value === 'bootout' || value === 'bootstrap')
    expect(order).toEqual(['bootout', 'bootstrap', 'bootstrap'])
  })

  it('returns manager failures in state detail without throwing', async () => {
    root = tempRoot()
    const service = createMutagenDaemonService(options(root, 'darwin', async () => { throw new Error('launchctl hung') }))
    await expect(service.describe()).resolves.toMatchObject({ loaded: false, detail: 'launchctl hung' })
    await expect(service.start()).resolves.toMatchObject({ detail: 'launchctl hung' })
  })
})

describe('systemd Mutagen service', () => {
  let root: string | undefined
  afterEach(() => { if (root) {rmSync(root, { recursive: true, force: true });} root = undefined })

  it('installs with daemon reload and enable-now and reports bus failures', async () => {
    root = tempRoot()
    const calls: Call[] = []
    const exec = async (command: string, args: readonly string[]) => {
      calls.push({ command, args })
      if (args[1] === 'show') {return { exitCode: 0, stdout: 'ActiveState=active\nSubState=running\nMainPID=123\nUnitFileState=enabled\nLoadState=loaded\n', stderr: '' }}
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const service = createMutagenDaemonService(options(root, 'linux', exec))
    const result = await service.install({ binaryPath: '/tmp/mutagen', dataDirectory: join(root, 'mutagen') })
    expect(result.action).toBe('installed')
    expect(calls.map((call) => call.args[1] ?? call.args[0])).toContain('daemon-reload')
    expect(calls.flatMap((call) => call.args)).toContain('--now')
    expect(MUTAGEN_SERVICE_SYSTEMD_UNIT).toBe(mutagenServicePaths({ stateRoot: join(root, 'state'), home: join(root, 'home'), platform: 'linux', env: {} }).label)

    const unavailable = createMutagenDaemonService(options(root, 'linux', async () => ({ exitCode: 1, stdout: '', stderr: 'Failed to connect to bus: No medium found' })))
    expect((await unavailable.describe()).detail).toContain('systemd --user is unavailable')
  })

  it('parses disabled and missing units and restarts an active service after changes', async () => {
    root = tempRoot()
    const calls: Call[] = []
    let show = 'ActiveState=active\nSubState=running\nMainPID=123\nUnitFileState=enabled\nLoadState=loaded\n'
    const exec = async (command: string, args: readonly string[]) => {
      calls.push({ command, args })
      if (args[1] === 'show') {return { exitCode: 0, stdout: show, stderr: '' }}
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const service = createMutagenDaemonService(options(root, 'linux', exec))
    await service.install({ binaryPath: '/tmp/mutagen-a', dataDirectory: join(root, 'mutagen') })
    calls.length = 0
    await service.install({ binaryPath: '/tmp/mutagen-b', dataDirectory: join(root, 'mutagen') })
    expect(calls.some((call) => call.args[1] === 'restart')).toBe(true)
    show = 'ActiveState=inactive\nSubState=dead\nMainPID=0\nUnitFileState=disabled\nLoadState=loaded\n'
    expect(await service.describe()).toMatchObject({ loaded: false, running: false, pid: null })
    show = ''
    const missing = createMutagenDaemonService(options(root, 'linux', async (_command, args) => args[1] === 'show'
      ? { exitCode: 1, stdout: 'LoadState=not-found\\nUnitFileState=\\n', stderr: 'Unit not found' }
      : { exitCode: 0, stdout: '', stderr: '' }))
    expect(await missing.describe()).toMatchObject({ loaded: false, running: false, pid: null, detail: 'Unit not found' })
  })

  it('ignores disable failures while uninstalling but reports reload failures', async () => {
    root = tempRoot()
    const calls: Call[] = []
    const exec = async (_command: string, args: readonly string[]) => {
      calls.push({ command: 'systemctl', args })
      if (args[1] === 'show') {return { exitCode: 1, stdout: '', stderr: 'Unit not found' }}
      if (args[1] === 'disable') {return { exitCode: 1, stdout: '', stderr: 'Unit not loaded' }}
      if (args[1] === 'daemon-reload') {return { exitCode: 1, stdout: '', stderr: 'reload failed' }}
      return { exitCode: 0, stdout: '', stderr: '' }
    }
    const service = createMutagenDaemonService(options(root, 'linux', exec))
    const result = await service.uninstall()
    expect(result.detail).toBe('reload failed')
    expect(calls.map((call) => call.args[1])).toEqual(['disable', 'daemon-reload', 'show'])
  })

  it('does nothing on unsupported platforms', async () => {
    root = tempRoot()
    const service = createMutagenDaemonService(options(root, 'freebsd', async () => ({ exitCode: 0, stdout: '', stderr: '' })))
    const state = await service.start()
    expect(state.platform).toBe('unsupported')
    expect(state.detail).toContain('freebsd')
    expect((await service.install({ binaryPath: '/tmp/mutagen', dataDirectory: '/tmp/data' })).action).toBe('unsupported')
  })
})
